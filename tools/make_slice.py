"""Builds a runnable data directory for a real-map slice from its history files.

usage: make_slice.py SLICE            (e.g. black_hills; reads data/history/SLICE, writes data/slices/SLICE)

The history files hold sourced FACTS (places.json, routes.json, jurisdictions.json) and the GUESSES the sim needs on top
(game.json). This script turns lat/lon into the sim's map coordinates (miles east and north, anchored so the slice lines up
with the full map at Cheyenne), applies the game numbers by kind or copies a node from the main data/world.json, converts
dated routes into edges, and writes world.json and scenario.json that `frontier_cli --data data/slices/SLICE` can run.
"""
import copy, json, math, os, re, shutil, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
slice_name = sys.argv[1] if len(sys.argv) > 1 else 'black_hills'
hist = os.path.join(ROOT, 'data', 'history', slice_name)
out = os.path.join(ROOT, 'data', 'slices', slice_name)


def load(path):
    return json.loads(re.sub(r'^\s*//.*$', '', open(path, encoding='utf-8').read(), flags=re.M))


def iso(d):
    """'1867' -> '1867-01-01', '1876-04' -> '1876-04-01'."""
    if d is None:
        return None
    parts = d.split('-')
    while len(parts) < 3:
        parts.append('01')
    return '-'.join(parts)


places = load(os.path.join(hist, 'places.json'))['places']
routes = load(os.path.join(hist, 'routes.json'))['routes']
juris = load(os.path.join(hist, 'jurisdictions.json'))['regions']
game = load(os.path.join(hist, 'game.json'))
main_world = load(os.path.join(ROOT, 'data', 'world.json'))
main_scn = load(os.path.join(ROOT, 'data', 'scenario.json'))
main_nodes = {n['id']: n for n in main_world['nodes']}

# Map projection: miles east and north, anchored at Cheyenne's position on the full map. 69.05 miles a degree of latitude;
# longitude shrinks with the cosine of a mid-corridor latitude.
anchor = next(p for p in places if p['id'] == 'cheyenne')
AX, AY = main_nodes['cheyenne']['x'], main_nodes['cheyenne']['y']
COS = math.cos(math.radians(41.5))


def project(lat, lon):
    return (round(AX + (lon - anchor['lon']) * COS * 69.17), round(AY + (lat - anchor['lat']) * 69.05))


HELPERS = {'copy_from', 'kind_defaults', 'contracts_like', 'closes', 'note', 'region_note'}
nodes, closes = [], []
for p in places:
    g = game['nodes'][p['id']]
    if 'copy_from' in g:
        n = copy.deepcopy(main_nodes[g['copy_from']])
    else:
        n = copy.deepcopy(game['kind_defaults'].get(g.get('kind_defaults', ''), {}))
    for k, v in g.items():
        if k not in HELPERS:
            n[k] = v
    if 'contracts_like' in g:
        src = main_nodes[g['contracts_like']]
        n['contracts'] = copy.deepcopy(src.get('contracts', {}))
        if 'extra_demand' not in g and 'extra_demand' in src:
            n['extra_demand'] = copy.deepcopy(src['extra_demand'])
    n['id'] = p['id']
    n['name'] = p['name']
    n['kind'] = p['kind']
    n['region'] = p['region']
    n['x'], n['y'] = project(p['lat'], p['lon'])
    if 'farm_open' in n:
        n['farm_open'] = iso(n['farm_open'])
    n.pop('transient_inflow', None)   # the flag no longer decides where outlaws come from
    nodes.append(n)
    if g.get('closes'):
        closes.append((p['id'], iso(g['closes']), n.get('garrison', 0)))

ids = {n['id'] for n in nodes}
edges = []
for r in routes:
    if r['a'] not in ids or r['b'] not in ids:
        continue
    e = {'a': r['a'], 'b': r['b']}
    if r.get('mode', 'trail') != 'trail':
        e['mode'] = r['mode']
    if 'miles' in r:
        e['miles'] = r['miles']
    if r.get('from'):
        e['from'] = iso(r['from'])
    if r.get('to'):
        e['until'] = iso(r['to'])
    e['note'] = r['name'] + (' - ' + r['note'] if r.get('note') else '')
    edges.append(e)

regions = {'_note': 'Jurisdictions of the slice; see data/history/%s/jurisdictions.json.' % slice_name}
for name in sorted({p['region'] for p in places}):
    j = juris.get(name, {})
    regions[name] = {'organized': iso(j['organized'])} if 'organized' in j else {}

interests = []
for it in main_world.get('interests', []):
    keep = [x for x in it.get('nodes', []) if x in ids]
    if it['hq'] in ids and len(keep) >= 2:
        it = dict(it)
        it['nodes'] = keep
        interests.append(it)
for it in interests:   # the Union Pacific also ran through Sidney in this slice
    if it['id'] == 'union_pacific' and 'sidney' in ids and 'sidney' not in it['nodes']:
        it['nodes'].insert(it['nodes'].index('ogallala') + 1, 'sidney')

world = {'_note': 'GENERATED by tools/make_slice.py from data/history/%s. Edit the history files and rerun, not this file.' % slice_name,
         'terrain_factor': main_world['terrain_factor'], 'regions': regions, 'nodes': nodes, 'edges': edges, 'interests': interests}

scn = {k: v for k, v in main_scn.items() if k in ('_note', 'seed', 'start', 'log_from', 'days', 'traders', 'max_traders', 'capital_min', 'capital_max', 'params')}
scn['_note'] = 'GENERATED by tools/make_slice.py from data/history/%s/game.json; a slice of the full scenario.' % slice_name
for k, v in game['scenario'].items():
    scn[k] = v
scn['gangs'] = []
scn['leaders'] = [l for l in main_scn.get('leaders', []) if l['home'] in ids]
campaigns = list(game.get('campaigns', []))
for pid, day, men in closes:
    campaigns.append({'name': 'Post closed', 'from': day, 'nodes': [pid], 'garrison_add': -men,
                      'cause': 'the Army gave up the post (date unverified)'})
scn['campaigns'] = campaigns
scn['shocks'] = [s for s in main_scn.get('shocks', []) if s['name'] in game.get('keep_shocks', []) and s.get('node', next(iter(ids))) in ids]

os.makedirs(out, exist_ok=True)
shutil.copy(os.path.join(ROOT, 'data', 'goods.json'), os.path.join(out, 'goods.json'))
json.dump(world, open(os.path.join(out, 'world.json'), 'w', encoding='utf-8'), indent=1)
json.dump(scn, open(os.path.join(out, 'scenario.json'), 'w', encoding='utf-8'), indent=1)
print('%s: %d nodes, %d edges, %d campaigns -> %s' % (slice_name, len(nodes), len(edges), len(campaigns), out))
for n in nodes:
    print('  %-16s x %5d y %5d  %s' % (n['id'], n['x'], n['y'], n['region']))
